-- Drops columns nothing writes to. Schemas baselined at V18 may have been created without some of
-- them, so every drop checks information_schema first (MySQL has no DROP COLUMN IF EXISTS).

-- 1. Preserve legacy question -> section links (pre-V10) before dropping questions.section_id.
SET @has_col = (SELECT COUNT(*) FROM information_schema.columns
                WHERE table_schema = DATABASE() AND table_name = 'questions' AND column_name = 'section_id');
SET @sql = IF(@has_col > 0,
    'INSERT INTO section_questions (id, section_id, question_id, sequence_order, created_by, created_at, updated_at)
     SELECT UUID(), q.section_id, q.id,
            COALESCE((SELECT MAX(sq.sequence_order) FROM section_questions sq WHERE sq.section_id = q.section_id), 0)
              + ROW_NUMBER() OVER (PARTITION BY q.section_id ORDER BY q.created_at, q.id),
            ''system'', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
     FROM questions q
     WHERE q.section_id IS NOT NULL
       AND q.deleted_at IS NULL
       AND NOT EXISTS (SELECT 1 FROM section_questions e WHERE e.section_id = q.section_id AND e.question_id = q.id)',
    'SELECT 1');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- 2. Drop the foreign key on questions.section_id (its name was generated by MySQL).
SET @fk = (SELECT constraint_name FROM information_schema.key_column_usage
           WHERE table_schema = DATABASE() AND table_name = 'questions'
             AND column_name = 'section_id' AND referenced_table_name IS NOT NULL
           LIMIT 1);
SET @sql = IF(@fk IS NOT NULL, CONCAT('ALTER TABLE questions DROP FOREIGN KEY `', @fk, '`'), 'SELECT 1');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- 3. Drop the unused columns.
SET @sql = IF((SELECT COUNT(*) FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = 'questions' AND column_name = 'section_id') > 0,
    'ALTER TABLE questions DROP COLUMN section_id', 'SELECT 1');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

